import AppKit

/// Marker types from the nspasteboard.org convention. Clipboard managers that
/// follow the convention skip concealed and transient items.
enum PB {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    private static let passwordManagerPrefixes = [
        "com.1password",
        "com.agilebits",
        "com.bitwarden",
        "com.lastpass",
        "com.dashlane",
        "com.nordpass",
        "in.sinew.enpass",
        "com.keepersecurity",
        "com.apple.passwords"
    ]

    static func isPasswordManagerType(_ type: NSPasteboard.PasteboardType) -> Bool {
        let value = type.rawValue.lowercased()
        return passwordManagerPrefixes.contains { value.hasPrefix($0) }
    }
}

@MainActor
enum PasteboardWriter {
    /// Change count of the last write this app made, so the monitor can ignore
    /// its own concealed rewrites.
    static var lastOwnWrite: Int = -1

    @discardableResult
    static func write(_ text: String, concealed: Bool) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        if concealed {
            pasteboard.declareTypes([.string, PB.concealed, PB.source], owner: nil)
            pasteboard.setString(text, forType: .string)
            pasteboard.setData(Data(), forType: PB.concealed)
            pasteboard.setString(
                Bundle.main.bundleIdentifier ?? "app.clipvault.ClipVault",
                forType: PB.source
            )
        } else {
            pasteboard.declareTypes([.string], owner: nil)
            pasteboard.setString(text, forType: .string)
        }

        lastOwnWrite = pasteboard.changeCount
        return lastOwnWrite
    }

    @discardableResult
    static func writeImage(_ data: Data, uti: String, concealed: Bool) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let type = NSPasteboard.PasteboardType(uti)
        let source = Bundle.main.bundleIdentifier ?? "app.clipvault.ClipVault"

        if concealed {
            pasteboard.declareTypes([type, PB.concealed, PB.source], owner: nil)
            pasteboard.setData(data, forType: type)
            pasteboard.setData(Data(), forType: PB.concealed)
            pasteboard.setString(source, forType: PB.source)
        } else {
            pasteboard.declareTypes([type], owner: nil)
            pasteboard.setData(data, forType: type)
        }

        lastOwnWrite = pasteboard.changeCount
        return lastOwnWrite
    }
}
