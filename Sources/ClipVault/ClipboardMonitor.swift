import AppKit
import Combine
import CryptoKit
import ImageIO
import ClipVaultKit

/// The most recent clipboard change, shown in onboarding and the menu bar.
struct ClipEvent: Equatable {
    let date: Date
    let appName: String?
    let bundleID: String?
    let secretKind: String?
    let characterCount: Int
    let isImage: Bool
}

/// Polls the general pasteboard, classifies each change, conceals secrets and
/// records history. Polling is used (rather than private notifications) so the
/// app needs no Input Monitoring permission.
@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var concealedCount = 0
    @Published private(set) var imageSecretCount = 0
    @Published private(set) var lastSecretKind: String?
    @Published private(set) var lastConcealedAt: Date?
    @Published private(set) var lastEvent: ClipEvent?
    @Published var isPaused = false {
        didSet {
            if !isPaused {
                lastChangeCount = NSPasteboard.general.changeCount
            }
        }
    }

    private let store: HistoryStore
    private var timer: Timer?
    private var lastChangeCount: Int
    private var clearWork: DispatchWorkItem?
    private var pendingClearCount: Int?
    private let pollInterval: TimeInterval = 0.25

    init(store: HistoryStore) {
        self.store = store
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        // Quitting must not leave a secret behind: clear it now.
        if clearWork != nil, let pending = pendingClearCount,
           NSPasteboard.general.changeCount == pending {
            NSPasteboard.general.clearContents()
        }
        clearWork?.cancel()
        clearWork = nil
    }

    // MARK: - Polling

    private func poll() {
        guard !isPaused else { return }

        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if changeCount == PasteboardWriter.lastOwnWrite { return }
        guard let types = pasteboard.types else { return }
        if types.contains(PB.transient) || types.contains(PB.autoGenerated) { return }

        let front = NSWorkspace.shared.frontmostApplication
        let source = Source(name: front?.localizedName, bundleID: front?.bundleIdentifier)

        let rawText = pasteboard.string(forType: .string)

        // An image wins when its only text is a file path or URL, as written
        // by Finder, screenshot tools and some clipboard utilities.
        if rawText == nil || Self.isFileReference(rawText!, types: types),
           let imageData = imageData(from: pasteboard) {
            processImage(imageData, changeCount: changeCount, source: source)
            return
        }

        if let rawText {
            processText(rawText, types: types, changeCount: changeCount, source: source)
        }
    }

    static func isFileReference(_ text: String, types: [NSPasteboard.PasteboardType]) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains("\n"), trimmed.hasPrefix("file://") || trimmed.hasPrefix("/") else { return false }
        guard trimmed.hasPrefix("file://") || types.contains(.fileURL) else { return false }
        // Only image files: a copied document also carries its icon as an image.
        let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tif", "tiff", "gif", "webp", "bmp"]
        return imageExtensions.contains((trimmed as NSString).pathExtension.lowercased())
    }

    private struct Source {
        let name: String?
        let bundleID: String?

        var isIgnored: Bool {
            guard let bundleID else { return false }
            return Prefs.strings(Prefs.ignoredApps).contains(bundleID)
        }

        var alwaysConceals: Bool {
            guard let bundleID else { return false }
            return Prefs.strings(Prefs.alwaysConcealApps).contains(bundleID)
        }
    }

    private func processText(
        _ rawText: String,
        types: [NSPasteboard.PasteboardType],
        changeCount: Int,
        source: Source
    ) {
        let text = rawText.count > 200_000 ? String(rawText.prefix(200_000)) : rawText
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        let declaredConcealed = types.contains(PB.concealed)
            || types.contains(where: PB.isPasswordManagerType)
        var match = SecretDetector.detect(text, declaredConcealed: declaredConcealed)

        // Single-line text from a listed app (Passwords, Keychain Access) is a
        // secret even when no pattern matches.
        if match == nil, source.alwaysConceals, !text.contains(where: \.isNewline) {
            match = SecretMatch(kind: "Copied from \(source.name ?? "a protected app")")
        }

        lastEvent = ClipEvent(
            date: Date(),
            appName: source.name,
            bundleID: source.bundleID,
            secretKind: match?.kind,
            characterCount: text.count,
            isImage: false
        )

        let recordHistory = Prefs.bool(Prefs.keepHistory) && !source.isIgnored

        guard let match else {
            if recordHistory {
                store.add(text: text, sourceApp: source.name, bundleID: source.bundleID, secretKind: nil)
            }
            return
        }

        if recordHistory && Prefs.bool(Prefs.keepSecrets) {
            store.add(text: text, sourceApp: source.name, bundleID: source.bundleID, secretKind: match.kind)
        }

        concealedCount += 1
        lastSecretKind = match.kind
        lastConcealedAt = Date()
        announceConcealed(match.kind)

        guard Prefs.bool(Prefs.concealSecrets) || declaredConcealed else { return }
        let clearCount: Int
        if declaredConcealed {
            clearCount = changeCount
        } else {
            clearCount = PasteboardWriter.write(text, concealed: true)
            lastChangeCount = clearCount
        }
        scheduleClear(after: clearCount)
    }

    /// Re-marks whatever text is on the clipboard as concealed and records it
    /// as a secret. Used by "Conceal clipboard now".
    @discardableResult
    func concealCurrentClipboard() -> Bool {
        guard let text = NSPasteboard.general.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return false
        }
        let kind = SecretDetector.detect(text)?.kind ?? "Concealed by you"
        if Prefs.bool(Prefs.keepHistory) && Prefs.bool(Prefs.keepSecrets) {
            store.add(text: text, sourceApp: "ClipVault", bundleID: Bundle.main.bundleIdentifier, secretKind: kind)
        } else if let plain = store.items.first(where: { !$0.isSecret && !$0.isImage && $0.text == text }) {
            store.delete(plain.id)
        }
        let count = PasteboardWriter.write(text, concealed: true)
        lastChangeCount = count
        scheduleClear(after: count)
        concealedCount += 1
        lastSecretKind = kind
        lastConcealedAt = Date()
        return true
    }

    // MARK: - Images and OCR

    private func imageData(from pasteboard: NSPasteboard) -> Data? {
        let candidates: [NSPasteboard.PasteboardType] = [
            .png,
            .tiff,
            NSPasteboard.PasteboardType("public.jpeg")
        ]
        for type in candidates {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                return data
            }
        }
        return nil
    }

    private func processImage(_ original: Data, changeCount: Int, source: Source) {
        lastEvent = ClipEvent(
            date: Date(),
            appName: source.name,
            bundleID: source.bundleID,
            secretKind: nil,
            characterCount: original.count,
            isImage: true
        )
        guard let processed = normalizedImage(original) else { return }

        // Secret screenshots are concealed even when nothing is recorded.
        var itemID: UUID?
        if Prefs.bool(Prefs.keepHistory) && !source.isIgnored {
            guard let added = store.addImage(
                processed.data,
                hash: processed.hash,
                uti: processed.uti,
                sourceApp: source.name,
                bundleID: source.bundleID,
                width: processed.width,
                height: processed.height
            ) else {
                return
            }
            // A repeated image was already read; keep its result and seal.
            guard added.isNew else { return }
            itemID = added.id
        }

        // Live OCR: the item appears immediately, its searchable text is
        // attached when Vision finishes.
        Task { [weak self] in
            let recognized = await OCRService.recognizeText(in: original)
            guard let self else { return }

            let capped = recognized.count > 20_000 ? String(recognized.prefix(20_000)) : recognized
            let match = capped.isEmpty ? nil : SecretDetector.detect(capped)

            if let match {
                self.imageSecretCount += 1
                self.lastSecretKind = "\(match.kind) in an image"
                self.lastConcealedAt = Date()
                self.announceConcealed("\(match.kind) in an image")

                // Late conceal: if the same image is still on the pasteboard,
                // mark it concealed for clipboard managers that read later.
                if Prefs.bool(Prefs.concealSecrets), NSPasteboard.general.changeCount == changeCount {
                    let newCount = PasteboardWriter.writeImage(
                        processed.data,
                        uti: processed.uti,
                        concealed: true
                    )
                    self.lastChangeCount = newCount
                    self.scheduleClear(after: newCount)
                }

                // "Keep secrets" also applies to text found inside images.
                if !Prefs.bool(Prefs.keepSecrets), let itemID {
                    self.store.delete(itemID)
                    return
                }
            }

            guard let itemID else { return }
            self.store.attachImageInsight(
                id: itemID,
                ocrText: capped.isEmpty ? nil : capped,
                secretKind: match?.kind,
                imageData: processed.data
            )
        }
    }

    private struct ProcessedImage {
        let data: Data
        let uti: String
        let width: Int
        let height: Int
        let hash: String
    }

    private func normalizedImage(_ original: Data) -> ProcessedImage? {
        guard let source = CGImageSourceCreateWithData(original as CFData, nil) else { return nil }

        let thumbnailOptions: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 1_600,
            kCGImageSourceShouldCacheImmediately: true
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(
            source,
            0,
            thumbnailOptions as CFDictionary
        ) else {
            return nil
        }

        let rep = NSBitmapImageRep(cgImage: image)
        var data: Data?
        var uti = "public.png"

        if let png = rep.representation(using: .png, properties: [:]), png.count <= 3_500_000 {
            data = png
        } else if let jpeg = rep.representation(
            using: .jpeg,
            properties: [.compressionFactor: 0.82]
        ) {
            data = jpeg
            uti = "public.jpeg"
        }

        guard let final = data else { return nil }
        let digest = SHA256.hash(data: final)
        let hash = digest.map { String(format: "%02x", $0) }.joined()

        return ProcessedImage(
            data: final,
            uti: uti,
            width: image.width,
            height: image.height,
            hash: hash
        )
    }

    // MARK: - Auto-clear

    /// Clears the pasteboard after the configured delay if it still holds the
    /// write identified by `changeCount`. Also used after pasting a secret
    /// from history.
    func scheduleClear(after changeCount: Int) {
        clearWork?.cancel()
        let seconds = Prefs.int(Prefs.clearSecretsSeconds)
        guard seconds > 0 else { return }

        pendingClearCount = changeCount
        let work = DispatchWorkItem { [weak self] in
            Task { @MainActor in
                self?.pendingClearCount = nil
                let pasteboard = NSPasteboard.general
                guard pasteboard.changeCount == changeCount else { return }
                pasteboard.clearContents()
                self?.lastChangeCount = pasteboard.changeCount
            }
        }
        clearWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + .seconds(max(5, seconds)), execute: work)
    }

    private func announceConcealed(_ kind: String) {
        if Prefs.bool(Prefs.concealSound) {
            NSSound(named: "Pop")?.play()
        }
        if Prefs.bool(Prefs.notifyOnConceal) {
            Notifier.postConcealed(kind: kind)
        }
    }
}
